import { z } from "zod";

export const DAYS = ["MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN"] as const;
export const PRIORITIES = ["HIGH", "MEDIUM", "LOW"] as const;

/** GET /api/v1/weekly?weekStart=2026-07-20 */
export const getWeeklyPlanSchema = z
  .object({
    weekStart: z
      .string()
      .regex(/^\d{4}-\d{2}-\d{2}$/, "weekStart must be YYYY-MM-DD"),
  })
  .strict();

/** POST /api/v1/weekly/tasks */
export const createWeeklyTaskSchema = z
  .object({
    weekStart: z
      .string()
      .regex(/^\d{4}-\d{2}-\d{2}$/, "weekStart must be YYYY-MM-DD"),
    title: z.string().min(1, "Title is required").max(200),
    description: z.string().max(2000).optional().nullable(),
    day: z.enum(DAYS),
    priority: z.enum(PRIORITIES).default("MEDIUM"),
    category: z.string().trim().min(1, "Category is required").max(50).default("General"),
    duration: z.number().int().min(15).max(720).default(60),
    startTime: z.string().max(20).optional().default("09:00 AM"),
    repeatWeekly: z.boolean().optional().default(false),
  })
  .strict();

/** PATCH /api/v1/weekly/tasks/:id */
export const updateWeeklyTaskSchema = z
  .object({
    title: z.string().min(1).max(200).optional(),
    description: z.string().max(2000).optional().nullable(),
    day: z.enum(DAYS).optional(),
    priority: z.enum(PRIORITIES).optional(),
    category: z.string().trim().min(1).max(50).optional(),
    duration: z.number().int().min(15).max(720).optional(),
    startTime: z.string().max(20).optional(),
    repeatWeekly: z.boolean().optional(),
    completed: z.boolean().optional(),
  })
  .strict();

/** POST /api/v1/weekly/generate */
export const generateWeeklyPlanSchema = z
  .object({
    routineContext: z
      .string()
      .trim()
      .min(10, "Please provide more details about your routine (at least 10 characters)")
      .max(5000),
    instructions: z.string().trim().max(2000).optional().default(""),
    weekStart: z
      .string()
      .regex(/^\d{4}-\d{2}-\d{2}$/, "weekStart must be YYYY-MM-DD")
      .optional(),
  })
  .strict();

/** Sub-schema for single task item generated by AI */
export const aiTaskItemSchema = z.object({
  title: z.string().trim().min(1).max(200),
  description: z.string().trim().max(2000).optional().nullable(),
  startTime: z.string().trim().max(20),
  endTime: z.string().trim().max(20),
  duration: z.number().int().min(15).max(720).optional(),
  category: z.string().trim().min(1).max(50).default("General"),
  priority: z.enum(PRIORITIES).default("MEDIUM"),
  repeatWeekly: z.boolean().default(true),
});

/** Schema for AI provider response validation */
export const aiWeeklyPlanResponseSchema = z.object({
  summary: z.string().trim().min(1),
  studyRotation: z.string().trim().optional().nullable(),
  weekdaySchedule: z.array(aiTaskItemSchema),
  saturdaySchedule: z.array(aiTaskItemSchema),
  sundaySchedule: z.array(aiTaskItemSchema),
});

/** Single task to be bulk saved */
export const bulkSaveTaskItemSchema = z.object({
  title: z.string().trim().min(1, "Title is required").max(200),
  description: z.string().max(2000).optional().nullable(),
  day: z.enum(DAYS),
  priority: z.enum(PRIORITIES).default("MEDIUM"),
  category: z.string().trim().min(1, "Category is required").max(50).default("General"),
  duration: z.number().int().min(15).max(720).default(60),
  startTime: z.string().max(20).default("09:00 AM"),
  repeatWeekly: z.boolean().default(true),
  completed: z.boolean().optional().default(false),
});

/** POST /api/v1/weekly/bulk-save */
export const bulkSaveWeeklyTasksSchema = z
  .object({
    weekStart: z
      .string()
      .regex(/^\d{4}-\d{2}-\d{2}$/, "weekStart must be YYYY-MM-DD"),
    replaceExisting: z.boolean().optional().default(false),
    tasks: z.array(bulkSaveTaskItemSchema).min(1, "At least one task is required"),
  })
  .strict();

/** DELETE /api/v1/weekly/plan */
export const deleteWeeklyPlanSchema = z
  .object({
    weekStart: z
      .string()
      .regex(/^\d{4}-\d{2}-\d{2}$/, "weekStart must be YYYY-MM-DD"),
  })
  .strict();

export type GetWeeklyPlanDTO = z.infer<typeof getWeeklyPlanSchema>;
export type CreateWeeklyTaskDTO = z.infer<typeof createWeeklyTaskSchema>;
export type UpdateWeeklyTaskDTO = z.infer<typeof updateWeeklyTaskSchema>;
export type GenerateWeeklyPlanDTO = z.infer<typeof generateWeeklyPlanSchema>;
export type AITaskItem = z.infer<typeof aiTaskItemSchema>;
export type AIWeeklyPlanResponse = z.infer<typeof aiWeeklyPlanResponseSchema>;
export type BulkSaveTaskItem = z.infer<typeof bulkSaveTaskItemSchema>;
export type BulkSaveWeeklyTasksDTO = z.infer<typeof bulkSaveWeeklyTasksSchema>;
export type DeleteWeeklyPlanDTO = z.infer<typeof deleteWeeklyPlanSchema>;
